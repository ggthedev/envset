package lazy

import (
	"fmt"
	"sort"
	"strings"
)

// ToolSpec describes how to lazy-load a CLI tool.
type ToolSpec struct {
	// Name is the command name (e.g. "pyenv", "direnv").
	Name string
	// InitCmd is the eval expression that initializes the tool.
	// It should be a valid shell expression like: pyenv init - zsh
	InitCmd string
	// Shell is the target shell (zsh, bash, fish).
	Shell string
}

// knownTools maps tool name -> init command template.
// %SHELL% is replaced with the actual shell name.
var knownTools = map[string]string{
	"rbenv":   "rbenv init - %SHELL%",
	"pyenv":   "pyenv init - %SHELL%",
	"nodenv":  "nodenv init - %SHELL%",
	"fnm":     "fnm env --use-on-cd --shell %SHELL%",
	"zoxide":  "zoxide init %SHELL%",
	"thefuck": "thefuck --alias",
	"navi":    "navi widget %SHELL%",
	"tv":      "tv init %SHELL%",
}

// notLazyLoadable lists tools whose init installs a prompt or shell hook. A
// wrapper runs init only when you type the tool's name, so the prompt or hook
// would silently be missing until then.
var notLazyLoadable = map[string]string{
	"starship":   "it draws your prompt",
	"oh-my-posh": "it draws your prompt",
	"direnv":     "it hooks every directory change",
	"atuin":      "it hooks history and key bindings",
	"mcfly":      "it hooks history and key bindings",
}

// KnownToolNames returns the supported tool names, sorted.
func KnownToolNames() []string {
	names := make([]string, 0, len(knownTools))
	for k := range knownTools {
		names = append(names, k)
	}
	sort.Strings(names)
	return names
}

// Resolve looks up a tool and returns its ToolSpec for the given shell.
// If initCmd is provided, it overrides the built-in lookup.
func Resolve(toolName, shell, initCmd string) (ToolSpec, error) {
	switch shell {
	case "":
		shell = "zsh" // default
	case "zsh", "bash", "fish":
	default:
		return ToolSpec{}, fmt.Errorf("cannot generate a lazy wrapper for shell %q (want zsh, bash or fish)", shell)
	}
	if why, ok := notLazyLoadable[toolName]; ok {
		return ToolSpec{}, fmt.Errorf("%s can't be lazy-loaded: %s, so its init has to run at shell start; keep it in your interactive config as is", toolName, why)
	}
	if initCmd == "" {
		tpl, ok := knownTools[toolName]
		if !ok {
			return ToolSpec{}, fmt.Errorf("unknown tool %q; provide --init-cmd or use one of: %s",
				toolName, strings.Join(KnownToolNames(), ", "))
		}
		initCmd = strings.ReplaceAll(tpl, "%SHELL%", shell)
	}
	return ToolSpec{Name: toolName, InitCmd: initCmd, Shell: shell}, nil
}

// Generate produces the lazy-load wrapper function for the given spec.
func Generate(spec ToolSpec) string {
	switch spec.Shell {
	case "fish":
		return generateFish(spec)
	default:
		return generatePosix(spec)
	}
}

// Header is the first line of every generated wrapper; it identifies an
// existing wrapper for the tool so --write never appends a duplicate.
func Header(tool string) string {
	return fmt.Sprintf("# Lazy-load wrapper for %s (generated by envset lazy)", tool)
}

// generatePosix produces a zsh/bash compatible lazy-load wrapper.
func generatePosix(spec ToolSpec) string {
	// Remove the wrapper before init so init can define the real function.
	remove := "unfunction" // zsh
	if spec.Shell == "bash" {
		remove = "unset -f"
	}
	return fmt.Sprintf(`# Lazy-load wrapper for %s (generated by envset lazy)
%s() {
  %s %s 2>/dev/null
  eval "$(%s)"
  %s "$@"
}
`, spec.Name, spec.Name, remove, spec.Name, spec.InitCmd, spec.Name)
}

// generateFish produces a fish-compatible lazy-load wrapper.
func generateFish(spec ToolSpec) string {
	return fmt.Sprintf(`# Lazy-load wrapper for %s (generated by envset lazy)
function %s
  functions --erase %s
  %s | source
  %s $argv
end
`, spec.Name, spec.Name, spec.Name, spec.InitCmd, spec.Name)
}
